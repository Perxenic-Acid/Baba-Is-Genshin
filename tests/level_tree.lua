-- Pure nested navigation: any definition can be a parent or a puzzle.
assert(RW_LevelTreeSelfTest())
local d = RW_GetDefaultLevelDefinition()
local other = assert(RW_CreateLevelDefinition("other", d.initial_world))
local definitions = {[d.id]=d, other=other}
local root = assert(RW_CreateLevelTree(definitions, d.id))
definitions.other.initial_world.entities[1].x = 8
assert(root.definitions.other.initial_world.entities[1].x == 2)
local a = assert(RW_EnterLevel(root, "door", d.id))
local nested = assert(RW_EnterLevel(a, "door", "other"))
assert(#nested.stack == 2 and nested.next_instance_id == 4)
local back_a = assert(RW_ReturnLevel(nested))
assert(RW_GetActiveLevel(back_a).instance_id == RW_GetActiveLevel(a).instance_id
    and RW_GetActiveLevel(back_a).world ~= RW_GetActiveLevel(a).world)
local again = assert(RW_EnterLevel(back_a, "door", "other"))
assert(again.active_id == nested.active_id and again.next_instance_id == 4)
local back_root = assert(RW_ReturnLevel(back_a))
local sibling = assert(RW_EnterLevel(back_root, "sibling", d.id))
assert(sibling.active_id ~= a.active_id)
local function rejected(tree, slot, id, reason)
    local n, err = RW_EnterLevel(tree,slot,id)
    assert(n == nil and err == reason)
end
rejected(root,"",d.id,"invalid_slot")
rejected(root,1,d.id,"invalid_slot")
rejected(root,"door","missing","unknown_definition")
rejected(back_root,"door","other","slot_definition_mismatch")
local bad, reason = RW_UpdateActiveLevel(a, RW_GetActiveLevel(root))
assert(bad == nil and reason == "instance_identity_mismatch")
assert(RW_ReturnLevel(root) == nil and #root.stack == 0)
assert(not root.children[root.active_id] and root.next_instance_id == 2)
assert(not RW_CreateLevelTree({wrong=d}, "wrong"))
assert(not RW_CreateLevelTree({[d.id]=d}, "missing"))
print("PASS: nested identity allocation, parent-slot deduplication, retained snapshots and navigation rejection")
