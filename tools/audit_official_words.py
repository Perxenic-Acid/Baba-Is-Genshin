"""Audit the installed official editor vocabulary; no mod directories are scanned."""
import argparse
import hashlib
import re
from pathlib import Path

SOURCE = Path(r"C:\Program Files (x86)\Steam\steamapps\common\Baba Is You\Data\Editor\editor_objectlist.lua")
OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "OFFICIAL_WORDS.md"
IMPLEMENTED = set("is has write fear follow make eat become mimic play you push stop win defeat sink word safe hot melt open shut weak float shift more select and not text all empty level move sleep still lockedright lockedup lockedleft lockeddown right up left down turn deturn nudgeright nudgeup nudgeleft nudgedown pull swap phantom reverse fall fallright fallup fallleft on near nextto above below besideleft besideright facing without facedby seeing feeling hide".split())
SPECIAL_NOUNS = {"text", "all", "empty", "level", "group", "group2", "group3"}
CATEGORIES = {0: "noun", 1: "verb", 2: "property", 3: "prefix", 4: "negation", 5: "letter", 6: "conjunction", 7: "condition"}


def render():
    data = SOURCE.read_bytes()
    source = data.decode("utf-8")
    entries = re.findall(r'\[\d+\]\s*=\s*\{\s*name\s*=\s*"(text_[^"]+)"(.*?)(?=\n\t\[\d+\]|\Z)', source, re.S)
    rows = []
    nouns = []
    for name, body in entries:
        name = name[5:]
        category = int(re.search(r"\btype\s*=\s*(\d+)", body).group(1))
        if category == 0 and name not in SPECIAL_NOUNS:
            nouns.append(name)
            continue
        rows.append((CATEGORIES[category], name, "implemented within documented scope" if name in IMPLEMENTED else "pending"))
    lines = ["# Official word coverage", "", "Generated by `python tools/audit_official_words.py`; verify with `--check`.", "", f"Primary source: installed `Data/Editor/editor_objectlist.lua`, SHA256 `{hashlib.sha256(data).hexdigest()}`.", "", f"Official catalog: {len(entries)} text entries; {len(nouns)} ordinary noun entries, {len(rows)} syntax/special/property entries.", "", "`implemented` is an execution path within current engine scope, not a claim of complete original parity.", "Scoped LEVEL/virtual EMPTY gaps remain in the linked semantics documents. Ordinary nouns use the generic", "authored vocabulary mechanism; this audit does not globally register them or enlarge ALL in existing levels.", "A pending word is not complete merely because its name could be stored as a Text token.", "", "| Category | Word | Status |", "| --- | --- | --- |"]
    lines.extend(f"| {category} | {name.upper()} | {status} |" for category, name, status in sorted(rows))
    lines += ["", "Ordinary noun catalog:", "", ", ".join(n.upper() for n in sorted(nouns)), "", "User priority: remaining verbs, then conditions, prefixes, GROUP, and properties.", "Letter/number/accidental composition is deferred for a later decision.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != output:
            raise SystemExit("official word coverage is stale")
        print("official word coverage matches installed primary source")
    else:
        OUTPUT.write_text(output, encoding="utf-8")
        print(OUTPUT)


if __name__ == "__main__":
    main()
